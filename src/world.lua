function draw_chunk_blocks(chunk, x_offset, y_offset)
    local i = 1
    for c=0, 15, 1 do
        for l=0, 15, 1 do
          if(chunk[i]~=10)then
            f:draw(sprites[chunk[i]],(l*8)+x_offset,(c*8)+y_offset)
          end
          i = i + 1
        end
    end
    f:rgb(255,math.cos(sine_var)*128+128,255)
    f:rect1(0+x_offset,0+y_offset,128,128)
    f:rgb(255,255,255)
    i = 1
end

function draw_world(xpos,ypos)
    draw_chunk_blocks(world[current_chunk-9],-128-xpos,-128-ypos)
    draw_chunk_blocks(world[current_chunk-8],    -xpos,-128-ypos)
    draw_chunk_blocks(world[current_chunk-7], 128-xpos,-128-ypos)

    draw_chunk_blocks(world[current_chunk-1],-128-xpos,    -ypos)

    draw_chunk_blocks(world[current_chunk  ],    -xpos,    -ypos)

    draw_chunk_blocks(world[current_chunk+1], 128-xpos,    -ypos)

    draw_chunk_blocks(world[current_chunk+7],-128-xpos, 128-ypos)
    draw_chunk_blocks(world[current_chunk+8],    -xpos, 128-ypos)
    draw_chunk_blocks(world[current_chunk+9], 128-xpos, 128-ypos)
end

function world_updates()

    if (mouse_x>15) then
        mouse_offset_x = -16
        if (mouse_y>15) then
            mouse_chunk = current_chunk + 9
            mouse_offset_y = -16
        elseif (mouse_y<0) then
            mouse_chunk = current_chunk + -7
            mouse_offset_y = 16
        else
            mouse_chunk = current_chunk + 1
            mouse_offset_y = 0
        end
    elseif (mouse_x<0) then
        mouse_offset_x = 16
        if (mouse_y>15) then
            mouse_chunk = current_chunk + 7
            mouse_offset_y = -16
        elseif (mouse_y<0) then
            mouse_chunk = current_chunk + -9
            mouse_offset_y = 16
        else
            mouse_chunk = current_chunk + -1
            mouse_offset_y = 0
        end
    else
        mouse_offset_x = 0
        if (mouse_y>15) then
            mouse_chunk = current_chunk + 8
            mouse_offset_y = -16
        elseif (mouse_y<0) then
            mouse_chunk = current_chunk + -8
            mouse_offset_y = 16
        else
            mouse_chunk = current_chunk
            mouse_offset_y = 0
        end
    end

    block_break(world,mouse_chunk)
    block_place(world,mouse_chunk)
end

